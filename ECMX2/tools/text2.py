def _params(pg, c, T):
    if not c.par:
        return
    pg.h3("겔 물성 파라미터 — 무엇을 돌리면 무엇이 바뀌는가", "lay-params")
    pg.p(f"층위별 물질 목록과 별도로, 조성·조건을 바꿨을 때 겔의 물성이 어떻게 움직이는지를 "
         f"<b>{len(c.par)}건</b> 정리했다. 이 표는 '무엇을 사는가'가 아니라 "
         "'산 것을 어떻게 맞추는가'에 답한다.")
    pg.raw(B.box("이 표를 읽을 때 주의할 것 — G′과 E는 다른 값이다", """
<p><b>G′(저장탄성률)</b>은 겔을 좌우로 흔들었을 때 되밀어 주는 정도를 진동 유변계로 잰 값이고,
<b>E(영률)</b>은 위에서 눌렀을 때 버티는 정도를 압축 시험이나 원자현미경으로 잰 값이다.
측정 원리가 다르고 시료에 가하는 변형도 달라서 <b>서로 환산되지 않는다.</b>
문헌에서 '콜라겐 겔 강성'이라는 말이 나오면 먼저 어느 쪽인지부터 확인해야 하며,
이 표는 그래서 측정법 열을 비워 두지 않았다.</p>""", "note"))
    pg.raw(T.params_table(c.par, c.refs, c._meta,
                          f"콜라겐 겔 물성 파라미터 {len(c.par)}건 — 조건, 값, 측정법, 결과.",
                          c.tab()))


