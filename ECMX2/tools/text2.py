    fails = []
    for src, rows in (("지지체", c.scaf), ("배지", c.med)):
        for r in rows:
            blob = " ".join(str(v) for v in r.values())
            if "확보 실패" in blob or "정량 근거 없음" in blob:
                why = next((str(v) for v in r.values() if "확보 실패" in str(v)), "")
                fails.append((src, r.get("item_id"), r.get("name_ko"),
                              why[:150] if why else "정량 근거 없음"))
    if not fails:
        pg.p("확보 실패로 표시된 항목이 없다.")
        return
    pg.p(f"근거나 규격을 끝내 확보하지 못한 항목이 <b>{len(fails)}건</b>이다. "
         "비워 두거나 '추정'으로 채우는 대신 사유를 적어 남긴다. "
         "이 목록이 다음에 무엇을 확인해야 하는지를 그대로 알려 준다.")
    pg.raw(B.table(
        ["계통", "ID", "물질", "무엇을 확보하지 못했는가"],
        [[B.sysb(s), f'<span class="q">{B.esc(i)}</span>', B.esc(n), B.esc(w)]
         for s, i, n, w in fails[:60]],
        f"확보 실패 · 정량 근거 없음 항목 {len(fails)}건 중 상위 {min(60, len(fails))}건.",
        ["", "q", "", ""], "", c.tab()))


