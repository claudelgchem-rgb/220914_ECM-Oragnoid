def _n(c, rows, k):
    return sum(1 for r in rows if (r.get("necessity") or "").strip() == k)


def _d(term, gloss):
    return f'<b>{B.esc(term)}</b><span class="gl"> — {B.esc(gloss)}</span>'


# ══════════════════════════════════════════════════════════════
def write(pg, c, T, FC, FD, FE):
    _cover(pg, c)
    _headline(pg, c)
    _scope(pg, c, T, FC)
    if c.scaf:
        _collagen_choice(pg, c, T, FC)
        _layers(pg, c, T, FC, FD, FE)
        _recipe(pg, c, T, FC)
    _medium(pg, c, T, FD, FE)
    _totals(pg, c, T, FE)
    _open(pg, c)
    _method(pg, c)


