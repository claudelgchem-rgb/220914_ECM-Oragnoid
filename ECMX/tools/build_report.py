    for fn, label in files.items():
        p = os.path.join(BASE, fn)
        if not os.path.exists(p): continue
        t = open(p, encoding="utf-8", errors="replace").read()
        seen = set()
        for m in re.finditer(r"확보 실패[:：]\s*([^\n|]{10,300})", t):
            s = re.sub(r"\*\*|`|<[^>]+>", "", m.group(1)).strip(" .|")
            key = s[:60]
            if key in seen: continue
            seen.add(key)
            if " — " in s:
                item, why = s.split(" — ", 1)
            elif " - " in s:
                item, why = s.split(" - ", 1)
            else:
                item, why = s[:70], s[70:] or "사유 원문에 미분리 기재"
            out.append([label, item.strip()[:110], why.strip()[:200]])
    if not out:
        out = [["전체", "개별 산출물의 결측 기록", "각 산출물 .md의 '확보 실패' 절을 직접 참조"]]
