def _d(term, gloss):
    return f'<b>{B.esc(term)}</b><span class="gl"> — {B.esc(gloss)}</span>'


def _n(c, rows, k):
    return sum(1 for r in rows if (r.get("necessity") or "").strip() == k)


# ══════════════════════════════════════════════════════════════
def write(pg, c, T, FC, FD, FE, FM):
    _cover(pg, c)
    _headline(pg, c, FC)
    _scope(pg, c, T, FC)
    if c.scaf:
        _materials(pg, c, T, FC, FM)
        _layers(pg, c, T, FC, FD, FE, FM)
        _params(pg, c, T, FM)
        _recipe(pg, c, T, FC)
    if c.med:
        _medium(pg, c, T, FD, FE)
    _totals(pg, c, T, FE)
    _open(pg, c)
    _method(pg, c)


